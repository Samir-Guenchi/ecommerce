interface AddEditStoreScreenProps {
  navigate?: (screenId: string, params?: any) => void;
  goBack?: () => void;
  storeId?: string;
}

const AddEditStoreScreen: React.FC<AddEditStoreScreenProps> = ({ navigate, goBack, storeId }) => {
  const isEditMode = !!storeId;
  const [loading, setLoading] = useState(isEditMode);
  const [saving, setSaving] = useState(false);
  const [storeName, setStoreName] = useState('');
  const [storeLocation, setStoreLocation] = useState('');
  const [storeDescription, setStoreDescription] = useState('');
  const [storeDomain, setStoreDomain] = useState('');
  const [useCustomDomain, setUseCustomDomain] = useState(false);
  const [autoGeneratedDomain, setAutoGeneratedDomain] = useState('');

  useEffect(() => {
    const loadStore = async () => {
      if (isEditMode && storeId) {
        try {
          setLoading(true);
          const response = await storeAPI.getStoreById(parseInt(storeId, 10));
          const store = response.store;
          setStoreName(store.name);
          setStoreLocation(store.location || '');
          setStoreDescription(store.description || '');
          setStoreDomain(store.domain || '');
          setUseCustomDomain(!!store.domain);
          if (store.domain) {
            setAutoGeneratedDomain(store.domain);
          }
        } catch (error: any) {
          Alert.alert('Error', error.message || 'Failed to load store.');
        } finally {
          setLoading(false);
        }
      }
    };

    loadStore();
  }, [isEditMode, storeId]);

  // Auto-generate domain when store name changes
  useEffect(() => {
    if (!isEditMode && storeName && !useCustomDomain) {
      const domainName = storeName
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-+|-+$/g, '');
      setAutoGeneratedDomain(`${domainName}.algeriepost.dz`);
    }
  }, [storeName, useCustomDomain, isEditMode]);

  const handleSave = async () => {
    if (!storeName) {
      Alert.alert('Error', 'Please enter a store name');
      return;
    }

    try {
      setSaving(true);
      const storeData: any = {
        name: storeName,
        location: storeLocation || undefined,
        description: storeDescription || undefined,
        status: 'draft',
      };

      // Domain handling
      if (useCustomDomain) {
        if (!storeDomain) {
          Alert.alert('Error', 'Please enter a custom domain or uncheck the custom domain option');
          setSaving(false);
          return;
        }
        storeData.domain = storeDomain;
      } else {
        // Use auto-generated domain (backend will generate it, but we can pass it for preview)
        storeData.domain = autoGeneratedDomain;
      }

      if (isEditMode && storeId) {
        await storeAPI.updateStore(parseInt(storeId, 10), storeData);
        Alert.alert('Success', 'Store updated successfully.');
      } else {
        await storeAPI.createStore(storeData);
        Alert.alert('Success', 'Store created successfully.');
      }

      if (goBack) {
        goBack();
      }
    } catch (error: any) {
      Alert.alert('Error', error.message || 'Failed to save store.');
    } finally {
      setSaving(false);
    }
  };

  if (loading) {
    return (
      <View style={[styles.container, styles.loadingContainer]}>
        <ActivityIndicator size="large" color="#000000" />
        <Text style={styles.loadingText}>Loading store...</Text>
      </View>
    );
  }

  return (
    <ScrollView
      style={styles.container}
      contentContainerStyle={styles.content}
      showsVerticalScrollIndicator={false}
    >
      <View style={styles.iconContainer}>
        <View style={styles.iconWrapper}>
          <StoreIcon />
        </View>
      </View>
      <Text style={styles.heading}>{isEditMode ? 'Edit Store' : 'Add Store'}</Text>
      <Text style={styles.subheading}>
        {isEditMode ? 'Update store information.' : 'Create a new store for your business.'}
      </Text>

      <View style={styles.formSection}>
        <View style={styles.inputContainer}>
          <Text style={styles.label}>Store Name *</Text>
          <TextInput
            style={styles.input}
            placeholder="Enter store name"
            placeholderTextColor="#999"
            value={storeName}
            onChangeText={setStoreName}
          />
        </View>

        <View style={styles.inputContainer}>
          <Text style={styles.label}>Location</Text>
          <TextInput
            style={styles.input}
            placeholder="Enter store location (optional)"
            placeholderTextColor="#999"
            value={storeLocation}
            onChangeText={setStoreLocation}
          />
        </View>

        <View style={styles.inputContainer}>
          <Text style={styles.label}>Description</Text>
          <TextInput
            style={[styles.input, styles.textArea]}
            placeholder="Enter store description (optional)"
            placeholderTextColor="#999"
            value={storeDescription}
            onChangeText={setStoreDescription}
            multiline
            numberOfLines={4}
            textAlignVertical="top"
          />
        </View>

        <View style={styles.inputContainer}>
          <View style={styles.domainHeader}>
            <Text style={styles.label}>Domain</Text>
            <TouchableOpacity
              style={styles.checkboxContainer}
              onPress={() => setUseCustomDomain(!useCustomDomain)}
            >
              <View style={[styles.checkbox, useCustomDomain && styles.checkboxChecked]}>
                {useCustomDomain && <Text style={styles.checkmark}>✓</Text>}
              </View>
              <Text style={styles.checkboxLabel}>Use custom domain</Text>
            </TouchableOpacity>
          </View>

          {useCustomDomain ? (
            <TextInput
              style={styles.input}
              placeholder="Enter custom domain (e.g., mystore.com)"
              placeholderTextColor="#999"
              value={storeDomain}
              onChangeText={setStoreDomain}
              autoCapitalize="none"
            />
          ) : (
            <View style={styles.domainPreview}>
              <Text style={styles.domainPreviewText}>
                {autoGeneratedDomain || 'Enter store name to see domain'}
              </Text>
              <Text style={styles.domainHint}>
                Domain will be auto-generated as: storename.algeriepost.dz
              </Text>
            </View>
          )}
        </View>
      </View>

      <TouchableOpacity
        style={[styles.submitButton, saving && styles.submitButtonDisabled]}
        onPress={handleSave}
        disabled={saving}
      >
        {saving ? (
          <ActivityIndicator color="#FFFFFF" />
        ) : (
          <Text style={styles.submitButtonText}>
            {isEditMode ? 'Update Store' : 'Create Store'}
          </Text>
        )}
      </TouchableOpacity>

      <Text style={styles.infoText}>
        {isEditMode
          ? 'Changes will be saved immediately.'
          : 'Your store will be created and you can start adding products.'}
      </Text>
    </ScrollView>
  );
};

