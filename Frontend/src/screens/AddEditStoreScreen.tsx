/**
 * AddEditStoreScreen — Algérie Poste E-Commerce Store Management
 */
import React, { useState, useEffect } from 'react';
import {
  View,
  Text,
  TextInput,
  TouchableOpacity,
  StyleSheet,
  ScrollView,
  ActivityIndicator,
} from 'react-native';
import { Picker } from '@react-native-picker/picker';
import Svg, { Path, Circle } from 'react-native-svg';
import AsyncStorage from '@react-native-async-storage/async-storage';
import { LinearGradient } from 'expo-linear-gradient';
import { storeAPI } from '../services/api.service';
import algeriaCities from '../data/algeria_cities.json';
import { getColors, SPACING } from '../theme';
import { useTheme } from '../theme/ThemeContext';
import { useTranslation } from '../i18n';
import StatusBanner from '../components/StatusBanner';
import { useStatusMessage } from '../components/useStatusMessage';
import { API_URL } from '../config/api.config';
import { CheckIcon } from '../components/ModernIcons';

const wilayas = [...new Set(algeriaCities.map((city: any) => city.wilaya_name))].sort();

/* ── Icons ── */
const SunIcon = () => (
  <Svg width={18} height={18} viewBox="0 0 24 24" fill="none">
    <Circle cx="12" cy="12" r="5" stroke="#FDB913" strokeWidth="2" />
    <Path d="M12 1V3M12 21V23M4.22 4.22L5.64 5.64M18.36 18.36L19.78 19.78M1 12H3M21 12H23M4.22 19.78L5.64 18.36M18.36 5.64L19.78 4.22" stroke="#FDB913" strokeWidth="2" strokeLinecap="round" />
  </Svg>
);
const MoonIcon = () => (
  <Svg width={18} height={18} viewBox="0 0 24 24" fill="none">
    <Path d="M21 12.79A9 9 0 1 1 11.21 3 7 7 0 0 0 21 12.79z" stroke="#3B82F6" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" />
  </Svg>
);
const BackArrowIcon = ({ color }: { color: string }) => (
  <Svg width={22} height={22} viewBox="0 0 24 24" fill="none">
    <Path d="M19 12H5M12 19L5 12L12 5" stroke={color} strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" />
  </Svg>
);

interface AddEditStoreScreenProps {
  navigate?: (screenId: string, params?: any) => void;
  goBack?: () => void;
  storeId?: string;
}

const AddEditStoreScreen: React.FC<AddEditStoreScreenProps> = ({ navigate, goBack, storeId }) => {
  const { mode, toggleTheme } = useTheme();
  const COLORS = getColors(mode);
  const { t, language, setLanguage, isRTL } = useTranslation();

  const isEditMode = !!storeId;
  const [loading, setLoading] = useState(isEditMode);
  const [saving, setSaving] = useState(false);
  const [storeName, setStoreName] = useState('');
  const [storeLocation, setStoreLocation] = useState('');
  const [storeDescription, setStoreDescription] = useState('');
  const [storeMetapixleid, setStoreMetapixleid] = useState('');
  const [storeTiktokPixleid, setStoreTiktokPixleid] = useState('');
  const [storeDomain, setStoreDomain] = useState('');
  const [useCustomDomain, setUseCustomDomain] = useState(false);
  const [autoGeneratedDomain, setAutoGeneratedDomain] = useState('');
  const { message, showSuccess, showError, clear } = useStatusMessage();

  // Document restriction
  const [docStatus, setDocStatus] = useState<string>('active');
  const [rejectionReason, setRejectionReason] = useState<string>('');
  const [checkingDocs, setCheckingDocs] = useState(true);

  const cycleLanguage = () => {
    const langs: ('en' | 'ar' | 'fr')[] = ['en', 'ar', 'fr'];
    const idx = langs.indexOf(language);
    setLanguage(langs[(idx + 1) % langs.length]);
  };

  // Check document verification status
  useEffect(() => {
    const checkDocStatus = async () => {
      try {
        const token = await AsyncStorage.getItem('accessToken') || await AsyncStorage.getItem('authToken');
        if (token) {
          const res = await fetch(`${API_URL}/users/me`, { headers: { Authorization: `Bearer ${token}` } });
          if (res.ok) {
            const user = await res.json();
            
            // Check if user is seller or both
            const isSeller = user.accountType === 'seller' || user.accountType === 'both';
            
            if (isSeller) {
              // For sellers, check document status
              if (user.sellerRegistration) {
                const vs = user.sellerRegistration.verificationStatus;
                if (vs === 'approved') setDocStatus('active');
                else if (vs === 'rejected') {
                  setDocStatus('rejected');
                  setRejectionReason(user.sellerRegistration.rejectionReason || '');
                } else if (vs === 'pending') setDocStatus('pending');
                else setDocStatus('not_uploaded');
              } else {
                // Seller without registration - allow but show warning
                setDocStatus('not_uploaded');
              }
            } else {
              // Not a seller - restrict
              setDocStatus('not_seller');
            }
          }
        }
      } catch (_) { }
      finally { setCheckingDocs(false); }
    };
    checkDocStatus();
  }, []);

  useEffect(() => {
    const loadStore = async () => {
      if (isEditMode && storeId) {
        try {
          setLoading(true);
          const response = await storeAPI.getStoreById(parseInt(storeId, 10));
          const store = response.store;
          setStoreName(store.name);
          setStoreLocation(store.location || '');
          setStoreDescription(store.description || '');
          setStoreMetapixleid(store.metapixleid || '');
          setStoreTiktokPixleid(store.tiktokpixleid || '');
          setStoreDomain(store.domain || '');
          setUseCustomDomain(!!store.domain);
          if (store.domain) setAutoGeneratedDomain(store.domain);
        } catch (error: any) {
          showError(error.message || 'Failed to load store.');
        } finally {
          setLoading(false);
        }
      }
    };
    loadStore();
  }, [isEditMode, storeId]);

  useEffect(() => {
    if (!isEditMode && storeName && !useCustomDomain) {
      const domainName = storeName.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
      setAutoGeneratedDomain(`${domainName}.algeriepost.dz`);
    }
  }, [storeName, useCustomDomain, isEditMode]);

  const handleSave = async () => {
    if (!storeName) { showError('Please enter a store name'); return; }
    try {
      setSaving(true);
      const storeData: any = {
        name: storeName,
        location: storeLocation || undefined,
        description: storeDescription || undefined,
        metapixleid: storeMetapixleid || undefined,
        tiktokpixleid: storeTiktokPixleid || undefined,
        status: 'draft',
      };
      if (useCustomDomain) {
        if (!storeDomain) { showError('Please enter a custom domain or uncheck the custom domain option'); setSaving(false); return; }
        storeData.domain = storeDomain;
      } else {
        storeData.domain = autoGeneratedDomain;
      }
      if (isEditMode && storeId) {
        await storeAPI.updateStore(parseInt(storeId, 10), storeData);
        showSuccess('Store updated successfully.');
      } else {
        const response = await storeAPI.createStore(storeData);
        const createdStore = response.store;
        const storefrontUrl = `http://localhost:5173/store/${createdStore.domain}`;
        showSuccess(`Store created! Storefront: ${storefrontUrl}`);
        console.log('✅ Store created successfully!');
        console.log('📍 Storefront URL:', storefrontUrl);
        console.log('🌐 Domain:', createdStore.domain);
      }
      if (goBack) goBack();
    } catch (error: any) {
      showError(error.message || 'Failed to save store.');
    } finally {
      setSaving(false);
    }
  };

  // Only restrict if not a seller or if documents are rejected
  const isRestricted = docStatus === 'not_seller' || docStatus === 'rejected';

  if (loading || checkingDocs) {
    return (
      <View style={[s.outer, { backgroundColor: COLORS.background }, s.center]}>
        <View style={{ backgroundColor: COLORS.surface, padding: 40, borderRadius: 22, borderWidth: 1, borderColor: COLORS.border, alignItems: 'center' }}>
          <ActivityIndicator size="large" color={COLORS.primary} />
          <Text style={{ marginTop: 16, fontSize: 14, color: COLORS.textMuted, fontWeight: '600' }}>Loading...</Text>
        </View>
      </View>
    );
  }

  return (
    <View style={[s.outer, { backgroundColor: COLORS.background }]}>
      <ScrollView contentContainerStyle={s.scrollContent} showsVerticalScrollIndicator={false}>

        {/* ─── Header ────────────────────────────── */}
        <View style={[s.header, isRTL && { flexDirection: 'row-reverse' }]}>
          <TouchableOpacity style={[s.backBtn, { backgroundColor: COLORS.surface, borderColor: COLORS.border }]} onPress={goBack} activeOpacity={0.7}>
            <BackArrowIcon color={COLORS.text} />
          </TouchableOpacity>
          <Text style={[s.headerTitle, { color: COLORS.text }]}>
            {isEditMode ? (t('store_edit') || 'Edit Store') : (t('store_add') || 'Add Store')}
          </Text>
          <View style={[s.headerControls, isRTL && { flexDirection: 'row-reverse' }]}>
            <TouchableOpacity
              style={[s.controlBtn, { backgroundColor: COLORS.surface, borderColor: COLORS.border }]}
              onPress={cycleLanguage}
              activeOpacity={0.7}
            >
              <Text style={{ fontSize: 11, fontWeight: '700', color: COLORS.text }}>{language.toUpperCase()}</Text>
            </TouchableOpacity>
            <TouchableOpacity
              style={[s.controlBtn, { backgroundColor: COLORS.surface, borderColor: COLORS.border }]}
              onPress={toggleTheme}
              activeOpacity={0.7}
            >
              {mode === 'dark' ? <SunIcon /> : <MoonIcon />}
            </TouchableOpacity>
          </View>
        </View>

        <StatusBanner message={message?.text ?? null} type={message?.type ?? 'error'} onDismiss={clear} />

        {/* ─── Document Warning (if pending/not uploaded) ────────────── */}
        {!isEditMode && (docStatus === 'pending' || docStatus === 'not_uploaded') && (
          <View style={[s.warningCard, { backgroundColor: COLORS.warning + '10', borderColor: COLORS.warning + '30' }]}>
            <View style={{ flexDirection: 'row', alignItems: 'center', gap: 12 }}>
              <Svg width={20} height={20} viewBox="0 0 24 24" fill="none">
                <Path d="M12 9v4M12 17h.01M21 12a9 9 0 11-18 0 9 9 0 0118 0z" stroke={COLORS.warning} strokeWidth="2" strokeLinecap="round" />
              </Svg>
              <View style={{ flex: 1 }}>
                <Text style={{ fontSize: 13, fontWeight: '700', color: COLORS.warning, marginBottom: 4 }}>
                  {docStatus === 'pending' ? 'Documents Under Review' : 'Documents Not Uploaded'}
                </Text>
                <Text style={{ fontSize: 12, color: COLORS.textSecondary, lineHeight: 16 }}>
                  {docStatus === 'pending' 
                    ? 'Your documents are being reviewed. You can create stores, but they may be restricted until approval.'
                    : 'Upload your seller documents to avoid restrictions. You can still create stores now.'}
                </Text>
              </View>
            </View>
          </View>
        )}

        {/* ─── Document Restriction (only for rejected or non-sellers) ────────────── */}
        {!isEditMode && isRestricted ? (
          <View style={[s.card, { backgroundColor: COLORS.surface, borderColor: COLORS.error + '40' }]}>
            <View style={{ alignItems: 'center', paddingVertical: 20 }}>
              <View style={{
                width: 64, height: 64, borderRadius: 32,
                backgroundColor: COLORS.error + '15',
                justifyContent: 'center', alignItems: 'center', marginBottom: 16,
              }}>
                <Svg width={28} height={28} viewBox="0 0 24 24" fill="none">
                  <Path d="M12 22s8-4 8-10V5l-8-3-8 3v7c0 6 8 10 8 10z" stroke={COLORS.error} strokeWidth="2" strokeLinecap="round" />
                  <Path d="M12 8v4M12 16h.01" stroke={COLORS.error} strokeWidth="2" strokeLinecap="round" />
                </Svg>
              </View>
              <Text style={{ fontSize: 20, fontWeight: '800', color: COLORS.error, marginBottom: 8, textAlign: 'center' }}>
                {docStatus === 'not_seller' ? 'Seller Account Required' : 'Store Creation Restricted'}
              </Text>
              <Text style={{ fontSize: 14, color: COLORS.textSecondary, textAlign: 'center', lineHeight: 20, marginBottom: 16, paddingHorizontal: 10 }}>
                {docStatus === 'not_seller' 
                  ? 'You need a seller account to create stores. Please switch to seller mode in settings.'
                  : 'Your documents were rejected. Please resubmit to create stores.'}
              </Text>
              {docStatus === 'rejected' && rejectionReason ? (
                <View style={{ backgroundColor: COLORS.error + '10', borderRadius: 12, padding: 12, marginBottom: 16, width: '100%' }}>
                  <Text style={{ fontSize: 12, fontWeight: '700', color: COLORS.error, marginBottom: 4 }}>Rejection Reason:</Text>
                  <Text style={{ fontSize: 13, color: COLORS.textSecondary, lineHeight: 18 }}>{rejectionReason}</Text>
                </View>
              ) : null}
              <TouchableOpacity
                style={{ backgroundColor: COLORS.primary, paddingHorizontal: 28, paddingVertical: 14, borderRadius: 14 }}
                onPress={() => navigate?.(docStatus === 'not_seller' ? 'userSettings' : 'documentUpload', docStatus === 'not_seller' ? {} : { accountType: 'seller' })}
                activeOpacity={0.8}
              >
                <Text style={{ color: '#FFF', fontWeight: '700', fontSize: 15 }}>
                  {docStatus === 'not_seller' ? 'Go to Settings' : (t('docState_resubmit') || 'Resubmit Documents')}
                </Text>
              </TouchableOpacity>
            </View>
          </View>
        ) : (
          <>
            {/* ─── Page Description ──────────────── */}
            <View style={{ marginBottom: 20 }}>
              <Text style={{ fontSize: 14, color: COLORS.textSecondary, lineHeight: 20 }}>
                {isEditMode
                  ? (t('store_editDesc') || 'Update your store information below.')
                  : (t('store_addDesc') || 'Create a new store for your business. Fill in the details below.')}
              </Text>
            </View>

            {/* ─── Form Card ────────────────────── */}
            <View style={[s.card, { backgroundColor: COLORS.surface, borderColor: COLORS.border }]}>
              {/* Store Name */}
              <View style={s.field}>
                <Text style={[s.label, { color: COLORS.text }]}>{t('store_name') || 'Store Name'} *</Text>
                <TextInput
                  style={[s.input, { backgroundColor: COLORS.background, borderColor: COLORS.border, color: COLORS.text }]}
                  placeholder={t('store_namePlaceholder') || 'Enter store name'}
                  placeholderTextColor={COLORS.textMuted}
                  value={storeName}
                  onChangeText={setStoreName}
                />
              </View>

              {/* Location */}
              <View style={s.field}>
                <Text style={[s.label, { color: COLORS.text }]}>{t('store_location') || 'Location'}</Text>
                <View style={[s.pickerWrap, { backgroundColor: COLORS.background, borderColor: COLORS.border }]}>
                  <Picker
                    selectedValue={storeLocation}
                    onValueChange={(val) => setStoreLocation(val)}
                    style={{ color: COLORS.text, height: 50 }}
                    dropdownIconColor={COLORS.textMuted}
                  >
                    <Picker.Item label={t('store_selectLocation') || 'Select store location'} value="" />
                    {wilayas.map((w) => (
                      <Picker.Item key={w} label={w} value={w} />
                    ))}
                  </Picker>
                </View>
              </View>

              {/* Meta Pixel ID */}
              <View style={s.field}>
                <Text style={[s.label, { color: COLORS.text }]}>Meta Pixel ID</Text>
                <TextInput
                  style={[s.input, { backgroundColor: COLORS.background, borderColor: COLORS.border, color: COLORS.text }]}
                  placeholder="Enter Meta Pixel ID (optional)"
                  placeholderTextColor={COLORS.textMuted}
                  value={storeMetapixleid}
                  onChangeText={setStoreMetapixleid}
                />
              </View>

              {/* TikTok Pixel ID */}
              <View style={s.field}>
                <Text style={[s.label, { color: COLORS.text }]}>TikTok Pixel ID</Text>
                <TextInput
                  style={[s.input, { backgroundColor: COLORS.background, borderColor: COLORS.border, color: COLORS.text }]}
                  placeholder="Enter TikTok Pixel ID (optional)"
                  placeholderTextColor={COLORS.textMuted}
                  value={storeTiktokPixleid}
                  onChangeText={setStoreTiktokPixleid}
                />
              </View>

              {/* Description */}
              <View style={s.field}>
                <Text style={[s.label, { color: COLORS.text }]}>{t('store_description') || 'Description'}</Text>
                <TextInput
                  style={[s.input, s.textArea, { backgroundColor: COLORS.background, borderColor: COLORS.border, color: COLORS.text }]}
                  placeholder={t('store_descPlaceholder') || 'Enter store description (optional)'}
                  placeholderTextColor={COLORS.textMuted}
                  value={storeDescription}
                  onChangeText={setStoreDescription}
                  multiline
                  numberOfLines={4}
                  textAlignVertical="top"
                />
              </View>

              {/* Domain */}
              <View style={s.field}>
                <View style={{ flexDirection: 'row', justifyContent: 'space-between', alignItems: 'center', marginBottom: 8 }}>
                  <Text style={[s.label, { color: COLORS.text, marginBottom: 0 }]}>{t('store_domain') || 'Domain'}</Text>
                  <TouchableOpacity
                    style={{ flexDirection: 'row', alignItems: 'center', gap: 6 }}
                    onPress={() => setUseCustomDomain(!useCustomDomain)}
                  >
                    <View style={[s.checkbox, { borderColor: COLORS.primary }, useCustomDomain && { backgroundColor: COLORS.primary, justifyContent: 'center', alignItems: 'center' }]}>
                      {useCustomDomain && <CheckIcon size={12} color="#FFFFFF" strokeWidth={3} />}
                    </View>
                    <Text style={{ fontSize: 12, color: COLORS.textSecondary, fontWeight: '500' }}>
                      {t('store_customDomain') || 'Use custom domain'}
                    </Text>
                  </TouchableOpacity>
                </View>

                {useCustomDomain ? (
                  <TextInput
                    style={[s.input, { backgroundColor: COLORS.background, borderColor: COLORS.border, color: COLORS.text }]}
                    placeholder="Enter custom domain (e.g., mystore.com)"
                    placeholderTextColor={COLORS.textMuted}
                    value={storeDomain}
                    onChangeText={setStoreDomain}
                    autoCapitalize="none"
                  />
                ) : (
                  <View style={[s.domainPreview, { backgroundColor: COLORS.background, borderColor: COLORS.border }]}>
                    <Text style={{ fontSize: 13, color: COLORS.text, fontWeight: '600', marginBottom: 4 }}>
                      {autoGeneratedDomain || (t('store_enterName') || 'Enter store name to see domain')}
                    </Text>
                    <Text style={{ fontSize: 11, color: COLORS.textMuted }}>
                      Domain: storename.algeriepost.dz
                    </Text>
                  </View>
                )}
              </View>
            </View>

            {/* ─── Submit Button ──────────────────── */}
            <TouchableOpacity
              style={[s.submitBtn, saving && { opacity: 0.6 }]}
              onPress={handleSave}
              disabled={saving}
              activeOpacity={0.8}
            >
              <LinearGradient
                colors={['#0D2C74', '#1E40AF']}
                start={{ x: 0, y: 0 }}
                end={{ x: 1, y: 0 }}
                style={s.submitGradient}
              >
                {saving ? (
                  <ActivityIndicator color="#FFFFFF" />
                ) : (
                  <Text style={s.submitText}>
                    {isEditMode ? (t('store_update') || 'Update Store') : (t('store_create') || 'Create Store')}
                  </Text>
                )}
              </LinearGradient>
            </TouchableOpacity>

            <Text style={{ fontSize: 12, color: COLORS.textMuted, textAlign: 'center', lineHeight: 18, marginTop: 8 }}>
              {isEditMode
                ? (t('store_updateHint') || 'Changes will be saved immediately.')
                : (t('store_createHint') || 'Your store will be created and you can start adding products.')}
            </Text>
          </>
        )}

      </ScrollView>
    </View>
  );
};

const s = StyleSheet.create({
  outer: { flex: 1 },
  center: { justifyContent: 'center', alignItems: 'center' },
  scrollContent: { paddingHorizontal: 20, paddingTop: 56, paddingBottom: 40 },

  header: { flexDirection: 'row', alignItems: 'center', marginBottom: 20 },
  backBtn: { width: 44, height: 44, borderRadius: 12, justifyContent: 'center', alignItems: 'center', borderWidth: 1, marginRight: 12 },
  headerTitle: { flex: 1, fontSize: 22, fontWeight: '800', letterSpacing: -0.3 },
  headerControls: { flexDirection: 'row', gap: 8 },
  controlBtn: { width: 40, height: 40, borderRadius: 10, justifyContent: 'center', alignItems: 'center', borderWidth: 1 },

  card: { borderRadius: 22, padding: 20, borderWidth: 1, marginBottom: 20 },
  warningCard: { borderRadius: 16, padding: 16, borderWidth: 1, marginBottom: 16 },

  field: { marginBottom: 18 },
  label: { fontSize: 13, fontWeight: '600', marginBottom: 8, letterSpacing: 0.2 },
  input: { borderWidth: 1, borderRadius: 14, paddingHorizontal: 16, paddingVertical: 14, fontSize: 14 },
  textArea: { minHeight: 100, paddingTop: 14 },
  pickerWrap: { borderWidth: 1, borderRadius: 14, overflow: 'hidden' },
  checkbox: { width: 20, height: 20, borderWidth: 2, borderRadius: 6, justifyContent: 'center', alignItems: 'center' },
  domainPreview: { borderWidth: 1, borderRadius: 14, padding: 16 },

  submitBtn: { borderRadius: 16, overflow: 'hidden', marginTop: 4 },
  submitGradient: { paddingVertical: 16, alignItems: 'center', justifyContent: 'center' },
  submitText: { color: '#FFFFFF', fontSize: 16, fontWeight: '800', letterSpacing: 0.5 },
});

export default AddEditStoreScreen;
